-- Schéma de la base turnover (PostgreSQL).
-- Appliqué par : python -m src.db.init_db (et au démarrage de l'API).
-- Idempotent (IF NOT EXISTS) : peut être rejoué sans risque.
-- Doit rester aligné avec src/db/models.py (vérifié par tests/test_db.py).

-- Entrées du modèle : une ligne par employé.
--   * jeu de données initial : fusion des 3 CSV, id_employee renseigné ;
--   * appels à /predict : id_employee NULL.
CREATE TABLE IF NOT EXISTS employes (
    id                                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employee                               INTEGER UNIQUE,
    -- SIRH
    age                                       INTEGER     NOT NULL,
    genre                                     VARCHAR(1)  NOT NULL,
    revenu_mensuel                            INTEGER     NOT NULL,
    statut_marital                            VARCHAR(50) NOT NULL,
    departement                               VARCHAR(50) NOT NULL,
    poste                                     VARCHAR(50) NOT NULL,
    nombre_experiences_precedentes            INTEGER     NOT NULL,
    annee_experience_totale                   INTEGER     NOT NULL,
    annees_dans_le_poste_actuel               INTEGER     NOT NULL,
    -- Sondage
    nombre_participation_pee                  INTEGER     NOT NULL,
    nb_formations_suivies                     INTEGER     NOT NULL,
    distance_domicile_travail                 INTEGER     NOT NULL,
    niveau_education                          INTEGER     NOT NULL,
    domaine_etude                             VARCHAR(50) NOT NULL,
    frequence_deplacement                     VARCHAR(50) NOT NULL,
    annees_depuis_la_derniere_promotion       INTEGER     NOT NULL,
    annes_sous_responsable_actuel             INTEGER     NOT NULL,
    -- Évaluations
    satisfaction_employee_environnement       INTEGER     NOT NULL,
    note_evaluation_precedente                INTEGER     NOT NULL,
    satisfaction_employee_nature_travail      INTEGER     NOT NULL,
    satisfaction_employee_equipe              INTEGER     NOT NULL,
    satisfaction_employee_equilibre_pro_perso INTEGER     NOT NULL,
    heure_supplementaires                     VARCHAR(3)  NOT NULL,
    augementation_salaire_precedente          INTEGER     NOT NULL,

    cree_le                                   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Sorties : le départ observé (jeu initial) ou prédit (API).
--   * observation : depart = valeur réelle, probabilite et seuil NULL ;
--   * prediction  : depart = décision du modèle, avec probabilite et seuil.
CREATE TABLE IF NOT EXISTS predictions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employe_id  INTEGER     NOT NULL REFERENCES employes (id) ON DELETE CASCADE,
    origine     VARCHAR(11) NOT NULL,
    depart      BOOLEAN     NOT NULL,
    probabilite DOUBLE PRECISION,
    seuil       DOUBLE PRECISION,
    cree_le     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_predictions_origine
        CHECK (origine IN ('observation', 'prediction')),
    CONSTRAINT ck_predictions_valeurs CHECK (
        (origine = 'observation' AND probabilite IS NULL AND seuil IS NULL)
        OR (origine = 'prediction' AND probabilite IS NOT NULL AND seuil IS NOT NULL)
    ),
    CONSTRAINT ck_predictions_probabilite
        CHECK (probabilite IS NULL OR (probabilite >= 0 AND probabilite <= 1))
);

CREATE INDEX IF NOT EXISTS ix_predictions_employe_id ON predictions (employe_id);

-- Un employé du jeu initial n'a qu'une seule observation.
CREATE UNIQUE INDEX IF NOT EXISTS ux_predictions_une_observation
    ON predictions (employe_id) WHERE origine = 'observation';

-- Journal des interactions utilisateurs <-> modèle : un appel à /predict = une ligne,
-- y compris les appels refusés (422) ou en erreur (500).
--   * entrees  : corps reçu (même invalide) ;
--   * erreurs  : détail de validation si 422 ;
--   * prediction_id : prédiction produite (NULL si refusée ou en erreur).
CREATE TABLE IF NOT EXISTS interactions (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id       VARCHAR(64)      NOT NULL UNIQUE,
    cree_le          TIMESTAMPTZ      NOT NULL DEFAULT now(),
    methode          VARCHAR(10)      NOT NULL,
    route            VARCHAR(200)     NOT NULL,
    code_http        INTEGER          NOT NULL,
    duree_ms         DOUBLE PRECISION NOT NULL,
    client           VARCHAR(100),
    user_agent       VARCHAR(300),
    entrees          JSONB,
    erreurs          JSONB,
    prediction_id    INTEGER REFERENCES predictions (id) ON DELETE SET NULL,
    version_api      VARCHAR(20)      NOT NULL,
    empreinte_modele VARCHAR(16)
);

CREATE INDEX IF NOT EXISTS ix_interactions_cree_le ON interactions (cree_le);
